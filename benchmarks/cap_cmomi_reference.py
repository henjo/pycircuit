"""Generate a golden cap_cmomi reference from the IHP Open PDK.

`cap_cmomi` is the interdigitated metal-oxide-metal capacitor: 314 lines
of Verilog-A, three terminals, eight named branches, and an RF equivalent
circuit (skin arm, main capacitance, core inductance, series resistance,
and an oxide/substrate shunt).  It is the smallest COMPLETE production
compact model in the PDK, which makes it the first rung in checking that
pycircuit's DSL can express a real one end to end.

What it exercises, all of which the DSL gained recently:

* eight NAMED branches, several sharing a node pair;
* `ddt` of a branch CURRENT (the two inductors) as well as of a voltage;
* parameter-only conditionals -- layer count, feed style, bottom-metal
  identity -- selecting between fitted coefficient sets;
* `floor` on a parameter expression, with the model's own epsilon nudge;
* clamps (`if (Rseries < 1e-3) Rseries = 1e-3`).

Writes ``pycircuit/circuit/tests/data/cap_cmomi_ihp_ac.json``.  The tests
read that file and never invoke ngspice.

Run:  python benchmarks/cap_cmomi_reference.py [--pdk PATH] [--out PATH]
"""

import argparse
import json
import os
import sys

import ngspice_ref


DEFAULT_OUT = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    '..', 'pycircuit', 'circuit', 'tests', 'data', 'cap_cmomi_ihp_ac.json')

#: feed codes, as `cap_cmomi.lib` defines them.
NONE, SAME, DOUBLE = 0, 1, 2

#: Configurations.  Chosen to reach every coefficient branch in the model
#: rather than to sample geometry evenly: each layer-count set, each
#: bottom-metal Cox set, each feed style, the clamp cases, and the large
#: feed=double device the header warns self-resonates in band.
CASES = [
    dict(name='w5_l5_N5_double', w=5e-6, l=5e-6, mmin=1, mmax=5,
         feed=DOUBLE, note='nominal 5x5, full stack, loop inductance'),
    dict(name='w5_l5_N5_same', w=5e-6, l=5e-6, mmin=1, mmax=5,
         feed=SAME, note='same-side feed: adds Cfeed, single-side L'),
    dict(name='w5_l5_N5_none', w=5e-6, l=5e-6, mmin=1, mmax=5,
         feed=NONE, note='no feed: double R set with single-side L'),
    dict(name='w10_l20_N5_double', w=10e-6, l=20e-6, mmin=1, mmax=5,
         feed=DOUBLE, note='rectangular, ratio != 1'),
    dict(name='w30_l60_N5_double', w=30e-6, l=60e-6, mmin=1, mmax=5,
         feed=DOUBLE, note='large: in-band self-resonance'),
    dict(name='w5_l5_N3_double', w=5e-6, l=5e-6, mmin=3, mmax=5,
         feed=DOUBLE, note='N=3 density/cfeed/R/skin set, M3-bottom Cox'),
    dict(name='w5_l5_N4_double', w=5e-6, l=5e-6, mmin=2, mmax=5,
         feed=DOUBLE, note='N=4 set, M2-bottom Cox'),
    dict(name='w5_l5_N2_same', w=5e-6, l=5e-6, mmin=4, mmax=5,
         feed=SAME, note='N=2 extrapolated set, M3-bottom Cox branch'),
    dict(name='w2_l2_N5_double', w=2e-6, l=2e-6, mmin=1, mmax=5,
         feed=DOUBLE, note='small: active_x/active_y floor clamps bite'),
    dict(name='w60_l3_N5_same', w=60e-6, l=3e-6, mmin=1, mmax=5,
         feed=SAME, note='wide and short: ratio << 1'),
]

DECK = """* cap_cmomi reference: {name}
.include {pdk}/models/cap_cmomi.lib

Iac PLUS 0 dc 0 ac 1
X1 PLUS 0 cap_cmomi w={w:g} l={l:g} mmin={mmin:d} mmax={mmax:d} feed={feed:d}

.control
osdi {pdk}/osdi/cap_cmomi.osdi
ac dec {ppd:d} {fmin:g} {fmax:g}
wrdata {{out}} v(PLUS)
.endc
.end
"""

FMIN, FMAX, PPD = 1e6, 1e11, 10


def run_case(pdk, case):
    deck = DECK.format(pdk=pdk, ppd=PPD, fmin=FMIN, fmax=FMAX, **case)
    freq, (v,) = ngspice_ref.run(deck, nvectors=1, complex_data=True,
                                 label=case['name'])
    ## `Iac PLUS 0` drives current from PLUS through the source to node 0,
    ## i.e. it injects into 0 and draws from PLUS, so the node voltage is
    ## -Z for a 1 A drive.  Store the IMPEDANCE, which is what a reader
    ## wants and what makes the sign convention explicit.
    return dict(f=freq,
                z_real=[-re for re, _ in v],
                z_imag=[-im for _, im in v])


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--pdk', default=ngspice_ref.DEFAULT_PDK)
    ap.add_argument('--out', default=os.path.normpath(DEFAULT_OUT))
    args = ap.parse_args(argv)

    if not os.path.isdir(args.pdk):
        ap.error('PDK not found at %s' % args.pdk)

    data = dict(
        source='IHP-Open-PDK SG13G2, cap_cmomi via OSDI',
        simulator=ngspice_ref.version(),
        note=('Two-terminal impedance Z(f) in ohms, SUB tied to ground by '
              'the wrapper subckt. Generated by '
              'benchmarks/cap_cmomi_reference.py; do not edit.'),
        cases={},
    )
    for case in CASES:
        sys.stdout.write('%-20s ' % case['name'])
        sys.stdout.flush()
        res = run_case(args.pdk, case)
        res.update({k: case[k] for k in
                    ('w', 'l', 'mmin', 'mmax', 'feed', 'note')})
        data['cases'][case['name']] = res
        ## The low-frequency capacitance is the model's trustworthy
        ## quantity, so report it as the run's sanity signal.
        z0 = complex(res['z_real'][0], res['z_imag'][0])
        c_lf = -1.0 / (2 * 3.141592653589793 * res['f'][0] * z0.imag)
        print('%d points, C(%.0f MHz) = %.3f fF'
              % (len(res['f']), res['f'][0] / 1e6, c_lf * 1e15))

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, 'w') as fh:
        json.dump(data, fh, indent=1, sort_keys=True)
    print('\nwrote %s (%d cases)' % (args.out, len(data['cases'])))


if __name__ == '__main__':
    main()
