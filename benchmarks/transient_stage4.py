"""STAGE 4 gates: step-control correctness.

`doc/transient_work_plan.md` stage 4.  The estimators are measured directly rather
than through a transient, because a transient conflates the estimator's accuracy with
the controller's reaction to it, and stage 4 changes both.

THE MEASUREMENT.  A local truncation error estimator claims to predict the error the
companion current commits at this step.  That error is exactly computable if the
charge is an analytic function:

    true = iq_computed - q'(t_n)

where `iq_computed` is what `compute_derivatives` produces from the charge history,
and `q'(t_n)` is the exact derivative.  `compute_lte` claims to estimate that same
quantity, so `est/true` is a pure measure of the estimator, with no controller, no
circuit and no solver in the way.  **An estimator is correct when this ratio is 1 at
every step ratio**, and the whole of 4c/4d is that it is not.

The driving function is a sinusoid, so every derivative is available in closed form
and `q'''` is nonzero (a polynomial of low degree would make the leading error term
vanish and every estimator would look perfect).

`--forceaccept` is the exception and measures a whole transient on purpose: gates 4b
and 4e are about what the CONTROLLER does with an estimate, not about the estimate,
and neither is observable from the estimator in isolation.

Usage::

    python -u benchmarks/transient_stage4.py --ratios       # 4c, 4d
    python -u benchmarks/transient_stage4.py --hscaling     # 4g-2
    python -u benchmarks/transient_stage4.py --pi           # 4a
    python -u benchmarks/transient_stage4.py --forceaccept  # 4b, 4e
"""

import argparse
import os
import sys

import numpy as np

_HERE = os.path.dirname(os.path.abspath(__file__))
_REPO = os.path.dirname(_HERE)
for _p in (_REPO, _HERE):
    if _p not in sys.path:
        sys.path.insert(0, _p)

from pycircuit.circuit import numeric
from pycircuit.circuit.integrator import (EulerIntegrator, TrapezoidalIntegrator,
                                          Gear2Integrator)

OMEGA = 2 * np.pi * 1e6
T_N = 0.371 / 1e6          # an arbitrary phase, not a zero crossing of any derivative


def q(t):
    return np.sin(OMEGA * t)


def dq(t):
    return OMEGA * np.cos(OMEGA * t)


def d3q(t):
    """Third derivative of the analytic charge, for the LOCAL reference (4g-b0)."""
    return -(OMEGA ** 3) * np.cos(OMEGA * t)


def est_over_true(integrator, h_curr, h_last, reference='local'):
    """(estimate, true, ratio) for one integrator at one pair of step sizes.

    `reference` selects what `true` means, and the distinction is the whole of
    gate 4g-b0.

      'propagated'  `iq_n - q'(t_n)` with `iq_{n-1}` taken from the recursion,
                    i.e. the error actually standing in the companion current.
                    For Euler and Gear2 this IS the local error, because their
                    `compute_derivatives` is a pure function of the charge
                    history and nothing propagates.  Trapezoidal is the only
                    method here whose companion current feeds back on itself.
      'local'       the classical local truncation error: the residual when
                    EXACT values are substituted for the history.  This is what
                    a step controller must estimate, because it is the part `h`
                    controls; the propagated part of trapezoidal error is an
                    undamped (-1)^n mode that shrinking `h` does not reduce.

    **The estimator is fed the real companion currents in both modes.**  Only
    the reference changes.  Feeding exact derivatives to the ESTIMATOR is the
    artefact recorded in this function's own note below and must not come back.

    The default is 'local', changed by gate 4g-b0.  That gate exists because
    changing a reference to make a number look better is exactly what the standing
    rule forbids, so it was measured first: for euler, gear2-classic and gear2-ywr
    the two references give **bit-identical** est/true at every h tested, because
    those methods' `compute_derivatives` is a pure function of the charge history
    and nothing propagates.  The default therefore changes no number that was
    previously trustworthy, and differs only for trapezoidal -- the one method with
    feedback in its companion current, and the one the distinction is about.

    THE HISTORY MUST BE THE HISTORY THE ESTIMATOR ACTUALLY GETS.  `iq_last` holds
    the *companion currents* produced by previous steps, not exact derivatives --
    for backward Euler that is `(q_{n-1} - q_{n-2})/h`, which approximates `q'` at
    the interval midpoint, not at the node.  Feeding exact derivatives instead
    measures a formula the integrator is never given, and the first version of this
    harness did exactly that: it reported backward Euler as a flat 0.501 at every
    step ratio, which is an artefact of the wrong input.

    So the companion currents are generated by running the method forward over a
    short prefix of exact charges, which is what a transient does -- the charge
    comes from the solve there and is prescribed here, but the `iq` recursion is
    identical.

    The charge history is exact, deliberately: that isolates the error the method
    commits at THIS step from any error accumulated earlier, which is what makes
    the ratio interpretable as a property of the estimator.
    """
    ## Walk back far enough to seed the recursion, then forward to t_n.
    n_prefix = 4
    times = [T_N - h_curr - h_last - (n_prefix - i) * h_last for i in range(n_prefix)]
    times += [T_N - h_curr - h_last, T_N - h_curr, T_N]
    steps = [times[i + 1] - times[i] for i in range(len(times) - 1)]

    ## Seed with the exact derivative at the first point; by t_n the recursion has
    ## long forgotten it for every method here (history depth <= 2).
    iq_hist = [dq(times[0])]
    for i in range(1, len(times)):
        h = steps[i - 1]
        h_prev = steps[i - 2] if i >= 2 else steps[0]
        q_c = np.array([q(times[i])])
        q_l = np.array([[q(times[i - 1])],
                        [q(times[i - 2] if i >= 2 else times[i - 1])]])
        iq_l = np.array([[iq_hist[-1]],
                         [iq_hist[-2] if len(iq_hist) >= 2 else iq_hist[-1]]])
        iq_i, _ = integrator.compute_derivatives(
            q_curr=q_c, C_curr=np.array([[1.0]]), h_curr=h,
            q_last=q_l, iq_last=iq_l, h_last=h_prev,
            is_first_step=False, toolkit=numeric)
        iq_hist.append(float(iq_i[0]))

    tn, t1, t2, t3 = times[-1], times[-2], times[-3], times[-4]
    q_curr = np.array([q(tn)])
    ## THREE past charges, matching what the transient's ring buffer now holds:
    ## stage 4g(b) raised Trapezoidal's `get_required_history()` to 3 and the
    ## harness must hand over the same history a real run would, or the estimator
    ## silently takes its two-past-point fallback and the gate measures the wrong
    ## branch.  It did exactly that once.
    q_last = np.array([[q(t1)], [q(t2)], [q(t3)]])
    ## The companion currents at t_{n-1} and t_{n-2}, as produced above.
    iq_last = np.array([[iq_hist[-2]], [iq_hist[-3]]])
    h_last2 = steps[-3]

    ## `true` -- see the `reference` note in the docstring.  In 'local' mode the
    ## history handed to compute_derivatives is exact; the ESTIMATOR below still
    ## receives `iq_last`, the real companion currents, in both modes.
    iq_ref = (np.array([[dq(t1)], [dq(t2)]]) if reference == 'local' else iq_last)
    iq, _geq = integrator.compute_derivatives(
        q_curr=q_curr, C_curr=np.array([[1.0]]), h_curr=h_curr,
        q_last=q_last, iq_last=iq_ref, h_last=h_last,
        is_first_step=False, toolkit=numeric)
    true = float(iq[0] - dq(tn))

    est, _p = integrator.compute_lte(
        q_curr=q_curr, h_curr=h_curr, q_last=q_last, iq_last=iq_last,
        h_last=h_last, is_first_step=False, toolkit=numeric, h_last2=h_last2)
    est = float(est[0])
    return est, true, (est / true if true != 0 else float('nan'))


def cmd_ratios(args):
    """Gates 4c and 4d: est/true must be flat in the step ratio."""
    h_base = 1e-9
    ratios = (0.25, 0.5, 1.0, 2.0, 4.0)
    configs = [
        ('euler', EulerIntegrator()),
        ('trap-classic', TrapezoidalIntegrator(lte_formula='classic')),
        ('trap-ywr', TrapezoidalIntegrator(lte_formula='ywr')),
        ('gear2-classic', Gear2Integrator(lte_formula='classic')),
        ('gear2-ywr', Gear2Integrator(lte_formula='ywr')),
    ]

    print('EST/TRUE vs STEP RATIO  (h_curr/h_last; h_curr = %.0e s)' % h_base)
    print('An exact estimator gives 1.000 in every column.')
    print()
    print('%-16s %s' % ('', ''.join('%12s' % ('r=%g' % r) for r in ratios)))
    worst = {}
    for name, integ in configs:
        row = []
        for r in ratios:
            h_last = h_base / r
            _e, _t, ratio = est_over_true(integ, h_base, h_last)
            row.append(ratio)
        worst[name] = row
        print('%-16s %s' % (name, ''.join('%12.4f' % v for v in row)))

    print()
    print('SPREAD (max/min across the ratio sweep) -- 1.00 is perfect:')
    for name, row in worst.items():
        finite = [v for v in row if np.isfinite(v)]
        spread = max(finite) / min(finite) if finite and min(finite) > 0 else float('nan')
        within5 = all(abs(v - 1.0) <= 0.05 for v in finite)
        print('  %-16s spread %10.2f   within 5%% of 1 everywhere: %s'
              % (name, spread, 'YES' if within5 else 'NO'))
    return 0


def cmd_hscaling(args):
    """Gate 4g-2: est/true must not scale as 1/h."""
    print('EST/TRUE vs STEP SIZE at a fixed ratio of 1.0')
    print('A correct estimator is flat here; scaling with h means the formula is')
    print('missing a power of h.')
    print()
    print('%-16s %s' % ('', ''.join('%12s' % ('h=%.0e' % h)
                                    for h in (1e-8, 1e-9, 1e-10))))
    for name, integ in (('euler', EulerIntegrator()),
                        ('trap-classic', TrapezoidalIntegrator(lte_formula='classic')),
                        ('trap-ywr', TrapezoidalIntegrator(lte_formula='ywr')),
                        ('gear2-classic', Gear2Integrator(lte_formula='classic')),
                        ('gear2-ywr', Gear2Integrator(lte_formula='ywr'))):
        row = [est_over_true(integ, h, h)[2] for h in (1e-8, 1e-9, 1e-10)]
        print('%-16s %s' % (name, ''.join('%12.4f' % v for v in row)))
    return 0


def cmd_pi(args):
    """Gate 4a: the PI step-size recursion must converge, not cycle.

    Driven open-loop on a synthetic error model: assume the true LTE scales as
    `h^p`, so the controller sees `err = (h/h_target)^p`. A stable controller
    drives `h` to `h_target`; an unstable one oscillates. This is the recursion the
    spectral radius in the plan refers to, exercised directly.
    """
    from pycircuit.circuit.stepcontroller import PIController

    p = 3.0
    h_target = 1.0
    ctrl = PIController()
    print('PI step-size recursion, order p=%g, target h=%g' % (p, h_target))
    print('%6s %14s %14s' % ('iter', 'h', 'err'))
    h = 0.3
    hs = []
    for i in range(40):
        err = (h / h_target) ** p
        ## THE REAL UPDATE LAW, not a transcription of it.  This block used to
        ## mirror the controller's arithmetic, which meant the gate could pass
        ## against a formula the simulator no longer used -- and it very nearly
        ## did: stage 4a's fix divides both gains by the order, and a mirrored
        ## copy would have gone on reporting the old limit cycle.
        factor = ctrl.pi_factor(err, ctrl.last_err, p)
        ctrl.last_err = err
        h = h * factor
        hs.append(h)
        if i < 8 or i >= 36:
            print('%6d %14.6f %14.6f' % (i, h, err))
    tail = hs[-8:]
    spread = max(tail) / min(tail)
    print()
    print('last 8 values of h: %s' % ' '.join('%.4f' % v for v in tail))
    print('spread over the tail: %.4f  (1.00 = settled, 2.0 = period-2 cycle)' % spread)
    print('GATE 4a (settles within 5%%): %s' % ('PASS' if spread <= 1.05 else 'FAIL'))
    return 0


## ---------------------------------------------------------------------------
## GATES 4b and 4e -- the force-accept path and the order-drop guard
## ---------------------------------------------------------------------------

MAX_REJECT = 3          # must track `transient.py`'s own constant


class _Spy:
    """Replays `transient.py`'s reject_count bookkeeping from outside it.

    The force-accept branch is inline in `_solve` and has no hook, so the count
    is reconstructed from the (accept, h) sequence the controller returns: four
    consecutive rejections at one time point is one force-accept.  Verified
    against direct instrumentation of that branch -- 78/78, 6/6 and 0/0 on three
    configurations -- before any of the numbers below were believed.

    **A force-accepted step is an accepted step.**  It enters the integrator
    history like any other, so it belongs in the ratio sequence.  The first
    version of this filtered on `accept` alone, dropped exactly the steps the
    gate is about, and reported a worst ratio of 97.7 where the truth was 10.0.
    """

    def __init__(self):
        from pycircuit.circuit.stepcontroller import IntegralController
        self.inner = IntegralController()
        self.h_accepted = []
        self.n_rejected = 0
        self.n_forced = 0
        self._consec = 0

    def set_relref(self, relref):
        self.inner.set_relref(relref)
        return self

    def evaluate_step(self, *args, **kwargs):
        accept, h_next = self.inner.evaluate_step(*args, **kwargs)
        forced = False
        if not accept:
            self.n_rejected += 1
            self._consec += 1
            if self._consec > MAX_REJECT:
                forced = True
                self.n_forced += 1
                self._consec = 0
        else:
            self._consec = 0
        if accept or forced:
            self.h_accepted.append(kwargs['h_curr'])
        return accept, h_next

    def ratios(self):
        h = self.h_accepted
        return [h[i + 1] / h[i] for i in range(len(h) - 1)]


def _fa_circuits():
    """A smooth drive, a stiff ringdown, and a drive with real discontinuities."""
    from pycircuit.circuit import SubCircuit, gnd
    from pycircuit.circuit.elements import R, C, L, VSin, VPulse

    def rc_vsin():
        c = SubCircuit()
        c['vs'] = VSin('a', gnd, va=1.0, freq=1e3)
        c['R'] = R('a', 'b', r=1e3)
        c['C'] = C('b', gnd, c=1e-7)
        return c, dict(tend=2e-3, timestep=1e-5)

    def stiff_rlc():
        c = SubCircuit()
        c['C1'] = C(1, gnd, c=1e-6)
        c['R1'] = R(1, 2, r=1.0)
        c['L1'] = L(2, gnd, L=1e-6)
        x0 = np.zeros(c.n)
        x0[c.get_node_index('1')] = 1.0
        x0[c.get_node_index('2')] = 1.0
        return c, dict(tend=5e-3, timestep=2e-4, x0=x0)

    def rc_pulse():
        c = SubCircuit()
        c['vs'] = VPulse('a', gnd, v1=0.0, v2=1.0, td=1e-5, tr=1e-7, tf=1e-7,
                         pw=2e-5, per=5e-5)
        c['R'] = R('a', 'b', r=1e3)
        c['C'] = C('b', gnd, c=1e-9)
        return c, dict(tend=3e-4, timestep=1e-6)

    return [('rc-vsin', rc_vsin), ('stiff-rlc', stiff_rlc), ('rc-pulse', rc_pulse)]


def cmd_forceaccept(args):
    """GATES 4b and 4e.  Does the escape hatch fire, and does it leave the bound?

    Reported per configuration: accepted steps, rejections, force-accepts, the
    worst ratio between consecutive ACCEPTED steps, and how many ratios sit
    outside variable-step BDF-2's zero-stability bound.

    Gate 4b's declared success is that no step ratio exceeds 2.414214 and that
    every force-accept warns.  The warning is asserted in the suite
    (`test_transient_repairs.py`); the ratio is the last column here.

    The `before` column is not reproducible from this file -- it needs the source
    as it stood at 3416492 (`git stash`, re-run, `git stash pop`), because the
    10x growth is inline in `_solve` with no hook.  What is reproducible, and what
    matters for a regression, is that the last column stays zero.
    """
    import warnings
    from pycircuit.circuit.transient import Transient
    from pycircuit.circuit.integrator import ZERO_STABILITY_RATIO

    names = [('euler', lambda: EulerIntegrator()),
             ('trap-classic', lambda: TrapezoidalIntegrator('classic')),
             ('trap-ywr', lambda: TrapezoidalIntegrator('ywr')),
             ('gear2-classic', lambda: Gear2Integrator('classic')),
             ('gear2-ywr', lambda: Gear2Integrator('ywr'))]
    ## 1e-3 IS NOT OPTIONAL and must stay first.  The original sweep for this
    ## gate ran 1e-4/1e-5/1e-6 only, concluded in writing that the shipped default
    ## no longer reaches the force-accept path, and was wrong: `Gear2('ywr')`
    ## reaches it at 1e-3 and was taking a step ratio of exactly 10.0 there.  A
    ## loose tolerance is what lets a step grow into trouble, so a sweep that only
    ## tightens cannot see this defect at all.
    reltols = [float(x) for x in (args.reltols or '1e-3,1e-4,1e-5').split(',')]

    print('Zero-stability bound on the step ratio: %.6f' % ZERO_STABILITY_RATIO)
    worst_overall = 0.0
    n_outside = 0
    for cname, builder in _fa_circuits():
        for reltol in reltols:
            print()
            print('=== %s, reltol=%g' % (cname, reltol))
            print('%-15s %8s %8s %8s %10s %10s'
                  % ('integrator', 'steps', 'reject', 'forced', 'worst', 'outside'))
            for name, make in names:
                cir, kw = builder()
                tran = Transient(cir, integrator=make(), reltol=reltol)
                spy = _Spy()
                tran.step_controller = spy
                with warnings.catch_warnings():
                    ## The force-accept warning is the subject of the `forced`
                    ## column; printing it 159 times would bury the table.
                    warnings.simplefilter('ignore', RuntimeWarning)
                    tran.solve(coupled_lte=False, **kw)
                rr = spy.ratios()
                outside = sum(1 for r in rr if r > ZERO_STABILITY_RATIO)
                worst_overall = max(worst_overall, max(rr))
                n_outside += outside
                print('%-15s %8d %8d %8d %10.4f %10d'
                      % (name, len(spy.h_accepted), spy.n_rejected, spy.n_forced,
                         max(rr), outside))
    print()
    print('worst accepted-step ratio anywhere: %.4f   ratios outside the bound: %d'
          % (worst_overall, n_outside))
    print('GATE 4b (no step ratio exceeds %.6f): %s'
          % (ZERO_STABILITY_RATIO, 'PASS' if n_outside == 0 else 'FAIL'))
    return 0 if n_outside == 0 else 1


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--ratios', action='store_true')
    p.add_argument('--hscaling', action='store_true')
    p.add_argument('--pi', action='store_true')
    p.add_argument('--forceaccept', action='store_true')
    p.add_argument('--reltols', default=None,
                   help='comma-separated, for --forceaccept '
                        '(default 1e-3,1e-4,1e-5 -- keep a LOOSE one, see the note '
                        'in cmd_forceaccept)')
    args = p.parse_args()
    if args.hscaling:
        return cmd_hscaling(args)
    if args.pi:
        return cmd_pi(args)
    if args.forceaccept:
        return cmd_forceaccept(args)
    return cmd_ratios(args)


if __name__ == '__main__':
    sys.exit(main())
